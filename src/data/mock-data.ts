const makeAnalysis = (spec: MockItemSpec): ScreenshotAnalysis | undefined => {
  if (spec.analysisFailure) return undefined;
  const textSignals =
    spec.summarySignals ??
    spec.ocrText
      ?.split(/(?:\n|[·|•])/)
      .map((signal) => signal.trim().slice(0, 48))
      .filter(Boolean)
      .slice(0, 3);
  const visualSignalByContentType: Record<ContentType, string[]> = {
    product: ["상품 이미지", "구매 정보 영역"],
    article: ["기사 화면", "본문 구성"],
    ui_reference: ["인터페이스 구성", "화면 배치"],
    social_post: ["소셜 게시물", "이미지 중심 구성"],
    conversation: ["대화 화면"],
    place: ["장소 이미지", "위치 정보 영역"],
    event: ["행사 화면", "일정 정보 영역"],
    video_frame: ["영상 화면 구성", "재생 장면"],
    document: ["문서 화면", "본문 구성"],
    other: ["주요 이미지", "화면 구성"],
  };
  return {
    title: spec.title,
    summary: spec.summary,
    summaryEvidence: spec.ocrText
      ? {
          basis: "ocr_text",
          signals: textSignals ?? [],
          explanation: "화면에서 읽은 문장과 숫자를 바탕으로 정리했어요.",
          modelVersion: "mock-text-summary-v1",
        }
      : {
          basis: "visual_embedding",
          signals: visualSignalByContentType[spec.contentType],
          explanation: "화면의 모습과 비슷한 장면을 바탕으로 정리했어요.",
          modelVersion: "mock-visual-summary-v1",
        },
    ocrText: spec.ocrText,
    suggestedIntent: spec.intent,
    intentConfidence: spec.confidence ?? 0.88,
    needsReview: (spec.confidence ?? 0.88) < 0.5,
    contentType: spec.contentType,
    contentTypeConfidence: Math.min((spec.confidence ?? 0.88) + 0.04, 0.98),
    keywords: spec.keywords ?? [],
    sensitive: spec.sensitive ?? false,
    sensitiveRegions: spec.sensitive
      ? [
          {
            id: `${spec.id}-sensitive-1`,
            kind: spec.sensitiveKind ?? "other",
            normalizedRect: { x: 0.08, y: 0.34, width: 0.84, height: 0.24 },
            confidence: 0.91,
            blurredByDefault: true,
          },
        ]
      : [],
    analyzerVersion: "mock-v1",
    analyzedAt: NOW,
  };
};

